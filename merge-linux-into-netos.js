// One-off/reproducible merge: fold the Linux-OS quiz bank (data/linux-os.js,
// data/linux-os.en.js) into the NetOS dataset as a single "Ngoài giáo trình"
// (outside the syllabus) week bucket, so there's one combined course instead
// of two separate top-level courses.
//
// Run: node merge-linux-into-netos.js
// Rewrites data/netos.js and data/netos.en.js in place (adds entries + one
// new week label at the end of QUIZ_WEEKS_ORDER_NETOS[_EN]). Safe to re-run:
// it strips any previously-merged linux-os entries first (tagged via
// `mergedFromLinuxOs: true`) before re-adding, so re-running after
// `node fetch-quiz.js` picks up fresh linux-os data without duplicating.

const fs = require('fs');
const path = require('path');

const WEEK_VI = 'Ngoài giáo trình: Trắc nghiệm tổng hợp Hệ điều hành Linux';
const WEEK_EN = 'Outside the syllabus: Combined Linux OS quiz';

function loadVars(file, names) {
  const src = fs.readFileSync(file, 'utf8');
  return new Function(src + `; return {${names.join(',')}};`)();
}

function mapLinuxToNetos(linuxQuestions, week) {
  return linuxQuestions.map((q) => ({
    type: 'mcq',
    text: q.text,
    options: q.options,
    correctIndex: q.correctIndex,
    explanation: q.explanation,
    week,
    mergedFromLinuxOs: true,
  }));
}

function mergeOne({ netosFile, netosDataVar, weeksVar, linuxFile, linuxDataVar, weekLabel }) {
  const { [linuxDataVar]: linuxData } = loadVars(linuxFile, [linuxDataVar]);
  const netosVars = loadVars(netosFile, [netosDataVar, weeksVar]);
  let netosData = netosVars[netosDataVar];
  let weeks = netosVars[weeksVar];

  // Strip any previous merge of this week to make this idempotent.
  netosData = netosData.filter((q) => !q.mergedFromLinuxOs);
  weeks = weeks.filter((w) => w !== weekLabel);

  const merged = netosData.concat(mapLinuxToNetos(linuxData, weekLabel));
  weeks.push(weekLabel);

  const mcqCount = merged.filter((q) => q.type === 'mcq').length;
  const cmdCount = merged.filter((q) => q.type === 'command').length;
  const jsOut =
    `// Auto-generated by generate.js + merge-linux-into-netos.js on ${new Date().toISOString()}\n` +
    `// Total: ${merged.length} (mcq: ${mcqCount}, command: ${cmdCount})\n` +
    `var ${netosDataVar} = ${JSON.stringify(merged, null, 1)};\n` +
    `var ${weeksVar} = ${JSON.stringify(weeks, null, 1)};\n`;
  fs.writeFileSync(netosFile, jsOut, 'utf8');
  console.log(`${netosFile}: ${netosData.length} + ${linuxData.length} = ${merged.length} questions, ${weeks.length} week buckets`);
}

mergeOne({
  netosFile: path.join(__dirname, 'data', 'netos.js'),
  netosDataVar: 'QUIZ_DATA_NETOS',
  weeksVar: 'QUIZ_WEEKS_ORDER_NETOS',
  linuxFile: path.join(__dirname, 'data', 'linux-os.js'),
  linuxDataVar: 'QUIZ_DATA_LINUX',
  weekLabel: WEEK_VI,
});

mergeOne({
  netosFile: path.join(__dirname, 'data', 'netos.en.js'),
  netosDataVar: 'QUIZ_DATA_NETOS_EN',
  weeksVar: 'QUIZ_WEEKS_ORDER_NETOS_EN',
  linuxFile: path.join(__dirname, 'data', 'linux-os.en.js'),
  linuxDataVar: 'QUIZ_DATA_LINUX_EN',
  weekLabel: WEEK_EN,
});
