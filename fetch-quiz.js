// Fetch all 15 Linux-OS quiz sets from voviethoang.com, extract embedded
// WQ_VARS.full_data JSON (questions + logic_map = correct answers), dedupe
// by normalized question text, and write a merged dataset for the local quiz app.
//
// Run: node fetch-quiz.js
// Output: ./data/questions.js  (const QUIZ_DATA = [...])
//         ./data/raw/bo-N.json (one raw full_data blob per set, for audit)

const https = require('https');
const fs = require('fs');
const path = require('path');

const BASE = 'https://voviethoang.com/bo-{N}-trac-nghiem-he-dieu-hanh-linux-online-co-dap-an';
const TOTAL_SETS = 15;
const RAW_DIR = path.join(__dirname, 'data', 'linux-os-raw');
const OUT_JS = path.join(__dirname, 'data', 'linux-os.js');

fs.mkdirSync(RAW_DIR, { recursive: true });

function fetchHtml(url) {
    return new Promise((resolve, reject) => {
        https.get(url, { headers: { 'User-Agent': 'Mozilla/5.0' } }, (res) => {
            if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
                return fetchHtml(res.headers.location).then(resolve, reject);
            }
            let data = '';
            res.on('data', (c) => (data += c));
            res.on('end', () => resolve(data));
        }).on('error', reject);
    });
}

// Extract the `full_data: {...}` object literal by brace-matching, then JSON.parse it.
function extractFullData(html) {
    const marker = 'full_data:';
    const start = html.indexOf(marker);
    if (start === -1) return null;
    let i = html.indexOf('{', start);
    if (i === -1) return null;
    let depth = 0, inStr = false, strChar = '', escaped = false;
    const begin = i;
    for (; i < html.length; i++) {
        const ch = html[i];
        if (inStr) {
            if (escaped) { escaped = false; }
            else if (ch === '\\') { escaped = true; }
            else if (ch === strChar) { inStr = false; }
        } else {
            if (ch === '"' || ch === "'") { inStr = true; strChar = ch; }
            else if (ch === '{') depth++;
            else if (ch === '}') { depth--; if (depth === 0) { i++; break; } }
        }
    }
    const jsonStr = html.slice(begin, i);
    return JSON.parse(jsonStr);
}

function normalize(text) {
    return (text || '')
        .toLowerCase()
        .normalize('NFC')
        .replace(/\s+/g, ' ')
        .replace(/[.,;:!?'"()]/g, '')
        .trim();
}

async function main() {
    const allQuestions = [];
    const seen = new Map(); // normalized question text -> question object

    for (let n = 1; n <= TOTAL_SETS; n++) {
        const url = BASE.replace('{N}', n);
        console.log(`Fetching Bo ${n}: ${url}`);
        let html;
        try {
            html = await fetchHtml(url);
        } catch (err) {
            console.error(`  FAILED: ${err.message}`);
            continue;
        }
        const fullData = extractFullData(html);
        if (!fullData) {
            console.error(`  No full_data found for set ${n}`);
            continue;
        }
        fs.writeFileSync(path.join(RAW_DIR, `bo-${n}.json`), JSON.stringify(fullData, null, 2), 'utf8');

        // full_data is keyed like "quiz_set_01" -> { metadata, questions, logic_map, scoring_rules }
        for (const setKey of Object.keys(fullData)) {
            const set = fullData[setKey];
            if (!set || !set.questions) continue;
            const logicMap = set.logic_map || {};
            for (const q of set.questions) {
                const letter = logicMap[q.id];
                if (letter === undefined) continue;
                const correctIndex = isNaN(letter)
                    ? letter.toString().toUpperCase().charCodeAt(0) - 65
                    : parseInt(letter, 10);

                const key = normalize(q.text);
                if (seen.has(key)) {
                    const existing = seen.get(key);
                    if (!existing.sourceSets.includes(n)) existing.sourceSets.push(n);
                    continue; // dedupe text/options/answer, keep set membership
                }

                const question = {
                    sourceSets: [n],
                    text: q.text,
                    options: q.options.map((o) => o.content),
                    correctIndex,
                    explanation: q.explanation || '',
                };
                seen.set(key, question);
                allQuestions.push(question);
            }
        }
    }

    console.log(`\nTotal unique questions after dedupe: ${allQuestions.length}`);
    const jsOut = `// Auto-generated by fetch-quiz.js on ${new Date().toISOString()}\nconst QUIZ_DATA_LINUX = ${JSON.stringify(allQuestions, null, 2)};\n`;
    fs.writeFileSync(OUT_JS, jsOut, 'utf8');
    console.log(`Written: ${OUT_JS}`);
}

main().catch((err) => {
    console.error(err);
    process.exit(1);
});
