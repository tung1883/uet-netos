// Builds the read-only "Reference" section (concepts/commands/how-tos), grouped
// by the same syllabus week structure as the NetOS quiz, from the same
// extract/ data already used to generate the quiz question bank, plus the
// hand-authored extract/reference-howtos.js walkthroughs.
//
// Run: node build-reference.js   (VI -> data/reference.js)
//      node build-reference.js --en   (EN -> data/reference.en.js, reads extract-en/)
const fs = require('fs');
const path = require('path');

const EN = process.argv.includes('--en');
const EXTRACT_DIR = EN ? 'extract-en' : 'extract';
const OUT_FILE = path.join(__dirname, 'data', EN ? 'reference.en.js' : 'reference.js');
const VAR_NAME = EN ? 'REFERENCE_DATA_EN' : 'REFERENCE_DATA';
const WEEKS = require(`./${EXTRACT_DIR}/weeks`);

const LINUX_FUNDAMENTALS = EN
  ? 'Linux Fundamentals (from the Linux OS quiz bank)'
  : 'Kiến thức nền tảng Linux (từ bộ trắc nghiệm HĐH Linux)';
const REVIEW_BUCKET = WEEKS.W11_TH20 || (EN ? 'Review' : 'Ôn tập');

// theory/*.js files don't carry a `week` field (they're flat MCQ-fact lists
// used for the exam-practice question bank) -- map each file to the week
// bucket its content best matches.
const THEORY_WEEK_MAP = {
  '01-linux-basics.js': LINUX_FUNDAMENTALS,
  '02-filesystem-permission.js': WEEKS.W3_TH3,
  '03-storage-process.js': WEEKS.W3_TH4,
  '04-networking-dns.js': WEEKS.W4_LT3,
  '05-security-services.js': WEEKS.W8_LT5,
  '06-mixed-review.js': REVIEW_BUCKET,
};

const HEADINGS = EN
  ? { concepts: 'Concepts', commands: 'Command reference', howtos: 'Step-by-step guides' }
  : { concepts: 'Khái niệm', commands: 'Lệnh tham khảo', howtos: 'Hướng dẫn thực hiện' };

function titleFromQuestion(text) {
  return text.replace(/\?\s*$/, '').trim();
}

// --- Load command files -> group by week ---
const commandsByWeek = new Map();
const cmdDir = path.join(__dirname, EXTRACT_DIR, 'commands');
for (const file of fs.readdirSync(cmdDir).sort()) {
  if (!file.endsWith('.js')) continue;
  const mod = require(path.join(cmdDir, file));
  const week = mod.week;
  if (!week) continue;
  if (!commandsByWeek.has(week)) commandsByWeek.set(week, []);
  for (const cmd of mod.commands) {
    commandsByWeek.get(week).push({
      type: 'command',
      name: cmd.name,
      purpose: cmd.description,
      flags: cmd.flags || [],
      examples: (cmd.scenarios || []).map((s) => s.accepted[0]),
    });
  }
}

// --- Load theory files -> convert Q/A into declarative concept facts, group by mapped week ---
const conceptsByWeek = new Map();
const theoryDir = path.join(__dirname, EXTRACT_DIR, 'theory');
const seenConceptText = new Set();
for (const file of fs.readdirSync(theoryDir).sort()) {
  if (!file.endsWith('.js')) continue;
  const week = THEORY_WEEK_MAP[file];
  if (!week) continue;
  const items = require(path.join(theoryDir, file));
  if (!conceptsByWeek.has(week)) conceptsByWeek.set(week, []);
  for (const q of items) {
    const key = (q.explanation || q.text).trim();
    if (seenConceptText.has(key)) continue;
    seenConceptText.add(key);
    conceptsByWeek.get(week).push({
      type: 'concept',
      title: titleFromQuestion(q.text),
      body: q.explanation || q.options[q.correctIndex],
    });
  }
}

// --- Load hand-authored how-to walkthroughs -> group by week ---
const howtosByWeek = new Map();
const howtos = require(path.join(__dirname, EXTRACT_DIR, 'reference-howtos'));
for (const h of howtos) {
  if (!howtosByWeek.has(h.week)) howtosByWeek.set(h.week, []);
  howtosByWeek.get(h.week).push({ type: 'howto', title: h.title, steps: h.steps });
}

// --- Assemble modules in syllabus order, extras + fundamentals at the end ---
const allWeeks = [LINUX_FUNDAMENTALS, ...WEEKS.ORDER];
const modules = [];
for (const week of allWeeks) {
  const sections = [];
  const concepts = conceptsByWeek.get(week);
  const commands = commandsByWeek.get(week);
  const howtoItems = howtosByWeek.get(week);
  if (concepts && concepts.length) sections.push({ heading: HEADINGS.concepts, items: concepts });
  if (commands && commands.length) sections.push({ heading: HEADINGS.commands, items: commands });
  if (howtoItems && howtoItems.length) sections.push({ heading: HEADINGS.howtos, items: howtoItems });
  if (sections.length) modules.push({ module: week, sections });
}

fs.mkdirSync(path.join(__dirname, 'data'), { recursive: true });
const itemCount = modules.reduce(
  (sum, m) => sum + m.sections.reduce((s2, sec) => s2 + sec.items.length, 0),
  0
);
const jsOut = `// Auto-generated by build-reference.js${EN ? ' --en' : ''} on ${new Date().toISOString()}\n// Modules: ${modules.length}, total items: ${itemCount}\nconst ${VAR_NAME} = ${JSON.stringify(modules, null, 1)};\n`;
fs.writeFileSync(OUT_FILE, jsOut, 'utf8');
console.log(`Written ${OUT_FILE}`);
console.log(`Modules: ${modules.length}, total items: ${itemCount}`);
for (const m of modules) {
  console.log(`  - ${m.module}: ${m.sections.map((s) => `${s.heading}(${s.items.length})`).join(', ')}`);
}
